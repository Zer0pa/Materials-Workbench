"""HiPhiveForceConstantFitAdapter — force constants from MLIP-MD data.

Fits second (FC2) and third (FC3) order force constants from displacement-force
data generated by an MLIP-MD trajectory. This lifts MLIP forces into the phonon
framework via the HiPhive cluster expansion approach.

Real backend: HiPhive (MIT) parked behind ``L15_FORCE_BACKEND=runpod_rest``.
Stub: Synthetic FC2/FC3 calibrated to be close to—but not identical to—the
Phonopy harmonic reference for the same fixture. This deliberately introduces a
small frequency RMSE to give the Phonopy-vs-HiPhive falsifier meaningful signal.

Literature calibration for frequency agreement
----------------------------------------------
Good MLIP-MD → HiPhive fits typically agree with Phonopy DFT to within 0.05–0.15 THz
across the Brillouin zone (Si, NaCl). Thermoelectrics (Bi2Te3) show larger
scatter ~0.1–0.3 THz due to anharmonicity.

Reference: Hellman et al. (2011) HiPhive; Brorsson et al. (2021) application.
"""

